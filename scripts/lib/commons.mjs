// Pure helpers for choosing openly licensed Wikimedia Commons photos (no network, unit-tested).
// Used by scripts/landmark-photos.mjs.

// Allowed: public domain (incl. US government works), CC0, CC BY and CC BY-SA. Never NC/ND/GFDL-only.
export function isAllowedLicense(shortName = "") {
  const s = String(shortName).trim();
  if (/\b(NC|ND)\b|non-?commercial|no-?deriv|GFDL|fair use/i.test(s)) return false;
  return /^(public domain|PD\b|PD-|CC0|CC[- ]BY(-SA)?[- ]\d)/i.test(s);
}

export const isPublicDomain = (shortName = "") => /^(public domain|PD\b|PD-|CC0)/i.test(String(shortName).trim());

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: "\"", "#39": "'", apos: "'", nbsp: " " };
export function plainText(html = "", max = 120) {
  const text = String(html).replace(/<[^>]*>/g, " ").replace(/&(amp|lt|gt|quot|#39|apos|nbsp);/g, (_, e) => ENTITIES[e])
    .replace(/\s+/g, " ").trim();
  return text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text;
}

const meta = (page, key) => page?.imageinfo?.[0]?.extmetadata?.[key]?.value || "";

// The best search result: a landscape JPEG, at least 1200 px wide, openly licensed, credited, not a map.
export function choosePhoto(pages = []) {
  return [...pages].sort((a, b) => (a.index ?? 0) - (b.index ?? 0)).find((page) => {
    const info = page?.imageinfo?.[0];
    if (!info || info.mime !== "image/jpeg" || !info.thumburl) return false;
    if (info.width < 1200 || info.width < info.height * 1.15) return false;
    if (/\b(map|diagram|logo|sign)\b/i.test(page.title || "")) return false;
    const license = meta(page, "LicenseShortName");
    if (!isAllowedLicense(license)) return false;
    return isPublicDomain(license) || plainText(meta(page, "Artist")).length > 0;
  }) || null;
}

// What the app stores for a chosen photo. `src` is the self-hosted copy the script downloads.
export function photoEntry(id, page, landmarkName) {
  const license = plainText(meta(page, "LicenseShortName"), 40);
  const artist = plainText(meta(page, "Artist"), 80);
  const description = plainText(meta(page, "ImageDescription"), 100);
  const year = (meta(page, "DateTimeOriginal").match(/\b(1[89]\d\d|20\d\d)\b/) || [])[1] || null;
  return {
    src: `assets/img/landmarks/${id}.jpg`,
    alt: description ? `${landmarkName}: ${description}` : `Photograph of ${landmarkName}`,
    credit: artist || (isPublicDomain(license) ? "Public domain" : "Unknown"),
    license,
    licenseUrl: meta(page, "LicenseUrl") || null,
    sourceUrl: page.imageinfo[0].descriptionurl,
    year
  };
}

export function renderPhotosModule(photos) {
  const sorted = Object.fromEntries(Object.entries(photos).sort(([a], [b]) => a.localeCompare(b)));
  return `// GENERATED by scripts/landmark-photos.mjs from Wikimedia Commons (see docs/trail-data-sources.md).
// Real landmark photos, self-hosted in assets/img/landmarks/. Only public domain, CC0, CC BY or CC BY-SA
// images are allowed, and the credit, license and source link must stay with each photo.
// Safe to hand-edit (e.g. improve alt text, or delete an entry and re-run the script to pick another).
export const LANDMARK_PHOTOS = Object.freeze(${JSON.stringify(sorted, null, 2)});
`;
}
